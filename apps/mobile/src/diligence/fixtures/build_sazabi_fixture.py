"""Build src/diligence/fixtures/sazabi-data.ts from the prototype's data.json and insights.js.
Run from the repo root: python3 apps/mobile/src/diligence/fixtures/build_sazabi_fixture.py
Copies the prototype's Sazabi research as is (minus long excerpts). No numbers are made up here."""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parents[5]
proto = root / "docs/features/20261024.02_first_steps_ui/prototype"
d = json.loads((proto / "data.json").read_text())
s = d["research"]["sazabi"]
def strip(o):
    if isinstance(o, dict):
        return {k: strip(v) for k, v in o.items() if k not in ("excerpt",)}
    if isinstance(o, list):
        return [strip(x) for x in o]
    return o
sections = strip(s["sections"])
used = set()
def walk(o):
    if isinstance(o, dict):
        if isinstance(o.get("source"), str): used.add(o["source"])
        for v in o.values(): walk(v)
    elif isinstance(o, list):
        for v in o: walk(v)
walk(sections); walk(s["setup"])
ids = {i for g in s["room_gaps"] for i in g["ids"]}
checklist = [c for c in d["checklist"] if c["id"] in ids or (c["kind"] == "document" and c["stages"].get("seed") == "yes" and not c.get("closing_at_early_stage"))]
room = s["room"]
src = (proto / "insights.js").read_text()
def grab(name):
    m = re.search(r"window\." + name + r" = (\{.*?\n\});", src, re.S)
    js = m.group(1)
    js = re.sub(r"(\n\s+)(\w+):", r'\1"\2":', js)
    js = re.sub(r"([{,]\s*)(mark|piece|title|text|refs):", r'\1"\2":', js)
    js = re.sub(r",(\s*[\]}])", r"\1", js)
    return json.loads(js)
out = {
    "slug": "sazabi",
    "setup": s["setup"],
    "greeting": s["greeting"],
    "sections": sections,
    "room_gaps": s["room_gaps"],
    "checklist": checklist,
    "sources": {k: {"url": d["sources"][k].get("url"), "title": d["sources"][k].get("title")} for k in sorted(used) if k in d["sources"]},
    "insights": grab("TC_INSIGHTS")["sazabi"],
    "about": grab("TC_ABOUT")["sazabi"],
    "room": {"files": room["files"], "holds": room["holds"],
             "partial": {"arrived": room["states"]["partial"]["arrived"], "answered": room["states"]["partial"]["answered"]},
             "full": {"arrived": room["states"]["full"]["arrived"], "answered": room["states"]["full"]["answered"]},
             "files_total": room["states"]["full"]["files_total"]},
}
header = "// Generated by build_sazabi_fixture.py from the prototype's data.json and insights.js. Do not edit by hand.\n"
(pathlib.Path(__file__).parent / "sazabi-data.ts").write_text(header + "const data = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\nexport default data;\n")
print(len(sections), len(checklist), len(out["sources"]), json.dumps(room["files"][0])[:200], json.dumps(room["holds"]["C02"])[:200], json.dumps(room["states"]["partial"]["answered"][:2])[:300])
