"""Generate TypeScript contracts by introspecting FastAPI, without running a server.

    python -m server.export_api
    python -m server.export_api --check

Only declared JSON responses are exported. Unstructured dictionaries stay unknown;
examples and stored data are never used to guess a contract.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

TS_PATH = Path(__file__).resolve().parents[1] / "packages/schema/src/api.ts"


def ts_type(node: dict[str, Any]) -> str:
    if "$ref" in node:
        name = node["$ref"].removeprefix("#/components/schemas/")
        return f"PythonModels[{json.dumps(name)}]"
    for key, separator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if key in node:
            return "(" + separator.join(ts_type(n) for n in node[key]) + ")"
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(v) for v in node["enum"])
    kind = node.get("type")
    if kind == "array":
        if "prefixItems" in node:
            return "[" + ", ".join(ts_type(n) for n in node["prefixItems"]) + "]"
        return f"({ts_type(node.get('items', {}))})[]"
    if kind == "object" or "properties" in node:
        props = node.get("properties", {})
        required = node.get("required", [])
        fields = [f"{json.dumps(k)}{'' if k in required else '?'}: {ts_type(v)};" for k, v in props.items()]
        extra = node.get("additionalProperties")
        if isinstance(extra, dict) or extra is True:
            record = f"Record<string, {ts_type(extra) if isinstance(extra, dict) else 'unknown'}>"
            return f"({{ {' '.join(fields)} }} & {record})" if fields else record
        return "{ " + " ".join(fields) + " }" if fields else "Record<string, unknown>"
    if isinstance(kind, list):
        return " | ".join(ts_type({"type": k}) for k in kind)
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def parameters(operation: dict, location: str) -> str:
    params = [p for p in operation.get("parameters", []) if p["in"] == location]
    return "{ " + " ".join(
        f"{json.dumps(p['name'])}{'' if p.get('required') else '?'}: {ts_type(p['schema'])};"
        for p in params
    ) + " }"


def typescript(document: dict | None = None) -> str:
    if document is None:
        from server.app import app
        document = app.openapi()
    out = ["// Generated by `python -m server.export_api` from FastAPI's OpenAPI schema. Do not edit.",
           "// Python annotations own these contracts. Run with --check to detect drift.", "",
           "export interface PythonModels {"]
    for name, node in sorted(document.get("components", {}).get("schemas", {}).items()):
        out.append(f"  {json.dumps(name)}: {ts_type(node)};")
    out += ["}", "", "export interface PythonAPI {"]
    for path, methods in sorted(document["paths"].items()):
        for method, operation in sorted(methods.items()):
            if method not in {"get", "post", "put", "patch", "delete"}:
                continue
            responses = [r.get("content", {}).get("application/json", {}).get("schema")
                         for status, r in operation.get("responses", {}).items() if status.startswith("2")]
            # Empty schemas belong to raw Response/FileResponse routes and the tRPC proxy.
            schemas = [s for s in responses if s]
            if not schemas:
                continue
            body = operation.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            out += [f"  {json.dumps(method.upper() + ' ' + path)}: {{",
                    f"    path: {parameters(operation, 'path')};",
                    f"    query: {parameters(operation, 'query')};",
                    f"    body: {ts_type(body) if body else 'never'};",
                    f"    output: {ts_type(schemas[0])};", "  };"]
    return "\n".join(out + ["}", ""])


def main(argv: list[str]) -> int:
    rendered = typescript()
    if TS_PATH.exists() and TS_PATH.read_text(encoding="utf-8") == rendered:
        return 0
    if "--check" in argv:
        print("stale: packages/schema/src/api.ts; run python -m server.export_api")
        return 1
    TS_PATH.write_text(rendered, encoding="utf-8")
    print("wrote packages/schema/src/api.ts")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
