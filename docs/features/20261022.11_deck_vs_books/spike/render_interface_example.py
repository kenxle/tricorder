#!/usr/bin/env python3
"""Write ../02_interface_example.md from the spike's saved output in out/.

    python3 render_interface_example.py

Every number, claim and gap in the page comes from out/*.json, written by
deck_vs_books_spike.py. The prose around it is fixed text in this script.
Rerun the spike first, then this, and the page stays true.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
PAGE = HERE.parent / "02_interface_example.md"


def load(name):
    return json.loads((OUT / f"{name}.json").read_text())


def table(res):
    rows = ["| Slide | Deck figure | Period | Books | How the books figure is made | Gap | Within tolerance |",
            "|---|---|---|---|---|---|---|"]
    for m in res["matches"]:
        books = m["books"]
        if isinstance(books, (int, float)):
            books = f"${books:,.0f}"
        unit = " points of the tallest bar" if m["basis"].startswith("bar height") else "%"
        gap = "" if m["gap_rel_pct"] is None else f"{m['gap_rel_pct']}{unit}"
        rows.append(f"| {m['slide']} | {m['figure']} | {m['period'] or ''} | {books} | {m['basis']} | {gap} | "
                    f"{'yes' if m['within_tolerance'] else 'no'} |")
    return "\n".join(rows)


def claim_lines(res):
    return "\n".join(f"- `{c['id']}` ({c['severity']}, `{c['check']['name']}`): {c['text']}" for c in res["claims"])


def block(obj):
    return "```json\n" + json.dumps(obj, indent=2) + "\n```"


def portable(claim):
    """Show the test deck by its file name, not this machine's path."""
    c = json.loads(json.dumps(claim))
    for s in c["sources"]:
        if s["uri"].startswith("/"):
            s["uri"] = "<test room>/01_overview/pitch_deck.pdf (spike/out/test_decks/" + Path(s["uri"]).name + ")"
    return c


def main():
    hv = load("hollis_voice")
    late = load("hollis_voice_chart_starts_late")
    quarterly = load("hollis_voice_chart_quarterly")
    unreadable = load("hollis_voice_chart_unreadable")
    nopnl = load("hollis_voice_no_pnl")
    bw = load("brasswick")
    clean = load("hollis_voice_clean")

    arr = next(c for c in hv["claims"] if c["value"] and c["value"]["label"] == "arr")
    window_ok = next(c for c in hv["claims"] if c["check"]["name"] == "deck_history_vs_metrics")
    late_flag = next(c for c in late["claims"] if c["check"]["name"] == "deck_history_vs_metrics")
    bw_flag = next(c for c in bw["claims"] if c["check"]["name"] == "deck_history_vs_metrics")
    late_window = next(m for m in late["matches"] if m["figure"] == "chart window")

    page = f"""# Interface example: what deck-vs-books writes

<!-- Generated by spike/render_interface_example.py from spike/out/*.json. Do not edit by hand. Rerun the spike, then the renderer. -->

This feature has no screen of its own. Its interface is the Claim and Gap JSON it adds to `out/<room>/redflags.json`, which the readout, the memo and the ask list read. So the prototype is this page: the real output of the spike ([spike/deck_vs_books_spike.py](spike/deck_vs_books_spike.py)) on the Hollis Voice room, on three test decks made from it, on a run with the P&L hidden, and on Brasswick. Nothing below was typed by hand. The renderer copies it from `spike/out/`.

Every claim on this page parsed as the skeleton's `schema.claim.Claim`, and every quote was found by the skeleton's quote checker (`schema/check_quotes.py`, revision `573567f`). The runs are in `spike/out/validate_*.txt`, written by [spike/validate_against_skeleton.py](spike/validate_against_skeleton.py).

The claim ids here are the spike's (`redflags-dvb-001`). In the product they come from `scans.base.Ids` and read `redflags-NNN`.

## 1. Hollis Voice, the real room: every revenue figure matched to a period

Run: `python3 spike/deck_vs_books_spike.py data_room/hollis_voice`. Output: [spike/out/hollis_voice.txt](spike/out/hollis_voice.txt).

As of {hv['as_of']}. First revenue month in the books: {hv['first_revenue_month']}.

{table(hv)}

Unmatched figures: {len(hv['unmatched'])}. The Hollis Voice deck shows three revenue figures (the ARR, the chart on slide 3 and the plan growth on slide 11), and all three map to a period in the P&L.

Claims:

{claim_lines(hv)}

The ARR claim in full. It is the deck-against-books half of PF2; see the PRD on how it sits beside `deck_claim_vs_named_cell`.

{block(arr)}

The chart window that reads clear on the real deck:

{block(window_ok)}

Second read of the books: `{hv['revenue_rows_cross_check']['file']}` summed by month against the P&L's `{hv['revenue_rows_cross_check']['pnl_line']}` differs by more than $1 in these months: {hv['revenue_rows_cross_check']['months_differing_by_more_than_1_dollar'] or 'none'}.

## 2. Test deck: the chart starts six months after the first revenue month

Made by `python3 spike/make_test_decks.py data_room/hollis_voice spike/out/test_decks`. It copies the room's deck and replaces slide 3 with a chart drawn from the P&L's own recurring revenue, starting at {late_window['period'].split(' to ')[0]}. The room is not changed. Output: [spike/out/hollis_voice_chart_starts_late.txt](spike/out/hollis_voice_chart_starts_late.txt).

{table(late)}

Months left out: {', '.join(late_window['left_out'])}.

{block(portable(late_flag))}

## 3. Test deck: quarters where the books hold months

Output: [spike/out/hollis_voice_chart_quarterly.txt](spike/out/hollis_voice_chart_quarterly.txt).

{claim_lines(quarterly)}

## 4. Test deck: a chart the script cannot read

The caption stays, the chart is a grey box. The window check still runs from the caption. The bar check becomes a gap. Output: [spike/out/hollis_voice_chart_unreadable.txt](spike/out/hollis_voice_chart_unreadable.txt).

{block(unreadable['gaps'])}

## 5. The P&L is missing

Run with `--hide 02_financials/financial_model.xlsx`. Label `{nopnl['label']}`. Output: [spike/out/hollis_voice_no_pnl.txt](spike/out/hollis_voice_no_pnl.txt).

Every deck figure is listed as unmatched, with the reason:

{block(nopnl['unmatched'])}

The gap that goes to the ask list:

{block(nopnl['gaps'])}

## 6. Brasswick: the planted partial-history flag (BF2)

Run: `python3 spike/deck_vs_books_spike.py data_room/brasswick`. Output: [spike/out/brasswick.txt](spike/out/brasswick.txt). The skeleton's scorer counts this claim as finding BF2 ([spike/out/validate_brasswick.txt](spike/out/validate_brasswick.txt)).

{table(bw)}

{block(bw_flag)}

Second read of the books: `{bw['revenue_rows_cross_check']['file']}` (subscription plus money recovered) against the P&L's `{bw['revenue_rows_cross_check']['pnl_line']}` differs in: {json.dumps(bw['revenue_rows_cross_check']['months_differing_by_more_than_1_dollar'])}. That is BF4, Ostley's annual invoice booked as September revenue. It belongs to the accounting-mislabels slice, not this one, and this feature does not write a claim for it.

## 7. The clean room reads clear

Label `{clean['label']}`.

{claim_lines(clean)}

Second read of the books: `{clean['revenue_rows_cross_check']['file']}` against `{clean['revenue_rows_cross_check']['pnl_line']}` differs in {json.dumps(clean['revenue_rows_cross_check']['months_differing_by_more_than_1_dollar'])}. In the clean room the pilot is not recurring, but the customer file's `mrr` column still carries its fee. The production check must pick the revenue-row columns that match the P&L line it compares against (see the PRD, DVB-R9).
"""
    PAGE.write_text(page)
    print(f"wrote {PAGE}")


if __name__ == "__main__":
    main()
