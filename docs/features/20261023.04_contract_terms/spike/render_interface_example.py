"""Render 02_interface_example.md from spike/out/*.json. Nothing in it is typed by hand.

    python3 docs/features/20261023.04_contract_terms/spike/render_interface_example.py
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
TARGET = HERE.parent / "02_interface_example.md"

RUNS = [
    ("hollis_voice", "Hollis Voice, the full room", "`data_room/hollis_voice`, unchanged."),
    ("test_30day", "Test contract: a 30-day cancellation counted as a year of ARR",
     "A copy of Hollis Voice plus one made-up order form for a counted customer: month to month, either party may end it on 30 days notice. Only claims about the test contract are shown."),
    ("test_one_year", "Test contract: the same customer with a one-year commitment",
     "The same copy and customer, with a 12-month term and a breach-only exit. Only claims about the test contract are shown."),
    ("test_change_of_control", "Test contract: a change-of-control clause",
     "The one-year contract plus a clause 3 that lets either party end it after the customer is acquired. Only claims about the test contract are shown."),
    ("contracts_only", "A folder that holds only contracts",
     "The three Hollis Voice contracts copied into an empty folder as contract_0.pdf to contract_2.pdf, names the room's patterns do not know."),
    ("seed_drop", "The Hollis Voice seed drop, which holds no contracts", "`data_room/hollis_voice_seed_drop`, unchanged."),
    ("brasswick", "Brasswick", "`data_room/brasswick`, unchanged. Its Norrgate statement of work is a supplier contract."),
]
SHOW_TERMS = ("customer_name", "effective_date", "term_end_date", "auto_renews", "non_renewal_notice_days",
              "termination_for_convenience", "convenience_notice_days", "exclusivity", "most_favoured_customer",
              "change_of_control")


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def main() -> None:
    lines = [
        "# Interface example: what contract-terms writes",
        "",
        "<!-- Generated by spike/render_interface_example.py from spike/out/*.json. Do not edit by hand. "
        "Rerun spike/contract_terms_spike.py, then the renderer. -->",
        "",
        "This feature has no screen of its own. Its interface is what it adds to `out/<room>/redflags.json`: claims, "
        "gaps, and two Panels, \"contract terms\" and \"contract checks\". The readout, the memo and the ask list read "
        "them. So the prototype is this page: the real output of `scans.redflags.contract_terms_full.check` on the "
        "rooms and on made-up test contracts, written by [spike/contract_terms_spike.py](spike/contract_terms_spike.py). "
        "Every quote below was checked by `schema/check_quotes.py` in the same run; the count of failures is shown "
        "for each run.",
        "",
        "Claim ids are the run's own (`redflags-NNN`, counted inside this check only).",
        "",
    ]
    for n, (key, title, how) in enumerate(RUNS, start=1):
        d = json.loads((OUT / f"{key}.json").read_text(encoding="utf-8"))
        qc = d["quote_check"]
        lines += [f"## {n}. {title}", "", how, "",
                  f"Quote check: {qc['claims']} claims in the run, {len(qc['failed'])} quotes not found.", ""]
        terms = next((p for p in d["panels"] if p["name"] == "contract terms"), None)
        if terms and key in ("hollis_voice", "test_change_of_control", "contracts_only"):
            lines += ["Terms read (from the \"contract terms\" Panel):", "",
                      "| Contract | Field | Status | Value | Page | Quote |", "|---|---|---|---|---|---|"]
            for r in terms["rows"]:
                if r[1] in SHOW_TERMS or r[1].startswith("other_clause") or r[1].startswith("amendment"):
                    lines.append("| " + " | ".join(cell(x) for x in r) + " |")
            lines.append("")
        checks = next((p for p in d["panels"] if p["name"] == "contract checks"), None)
        if checks and checks["rows"]:
            lines += ["Checks (from the \"contract checks\" Panel):", "",
                      "| Contract | Check | Result | Reason |", "|---|---|---|---|"]
            for r in checks["rows"]:
                lines.append(f"| {cell(r[1])} | `{r[2]}` | {r[3]} | {cell(r[4])} |")
            lines.append("")
        if d["claims"]:
            lines += ["Claims:", ""]
            for c in d["claims"]:
                lines.append(f"- `{c['id']}` ({c['severity']}, `{c['check']['name']}`, {c['confidence']}): {c['text']}")
                for s in c["sources"]:
                    lines.append(f"  - `{s['uri']}` {s['locator']}: \"{cell(s['quote'])}\"")
            lines.append("")
        if d["gaps"]:
            lines += ["Gaps:", ""]
            for g in d["gaps"]:
                lines.append(f"- {g['what']}. Why: {g['why']}. Would need: {g['would_need']} Piece: {g.get('piece')}.")
            lines.append("")
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
