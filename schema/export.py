"""Write schema/claim.schema.json and schema/ts/claim.ts from schema.claim.

    python -m schema.export          write both files
    python -m schema.export --check  exit 1 if either is stale (CI runs this)

The TypeScript types are what the readout page imports, so the page never
hand-types a field. `structured_output_schema()` gives the form Claude's
structured outputs accept: every property required, nullable where optional.
"""

from __future__ import annotations

import copy
import json
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from schema.claim import EXPORTED

HERE = Path(__file__).resolve().parent
JSON_PATH = HERE / "claim.schema.json"
TS_PATH = HERE / "ts" / "claim.ts"


def json_schema(mode: str = "validation") -> dict[str, Any]:
    """validation: what a writer may omit. serialization: what a reader always gets."""
    _, top = models_json_schema([(m, mode) for m in EXPORTED], ref_template="#/$defs/{model}")
    top["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    top["title"] = "Tricorder shared Claim schema"
    return top


def structured_output_schema(model: type[BaseModel]) -> dict[str, Any]:
    """A model's schema in the shape Claude's structured outputs take.

    Every object lists every property as required and forbids extra ones, and
    no numeric or length limits appear (FRAMEWORKS.md, "The shared Claim").
    """
    schema = copy.deepcopy(model.model_json_schema(ref_template="#/$defs/{model}"))

    def fix(node: Any) -> None:
        if isinstance(node, dict):
            if node.get("type") == "object" and "properties" in node:
                node["required"] = list(node["properties"])
                node["additionalProperties"] = False
            for key in ("default", "title", "minLength", "maxLength", "minimum", "maximum", "minItems", "maxItems"):
                node.pop(key, None)
            for v in node.values():
                fix(v)
        elif isinstance(node, list):
            for v in node:
                fix(v)

    fix(schema)
    return schema


# TypeScript ---------------------------------------------------------------


def _ts_type(node: dict[str, Any]) -> str:
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in node:
        return " | ".join(_ts_type(n) for n in node["anyOf"])
    if "enum" in node:
        return " | ".join(json.dumps(v) for v in node["enum"])
    if "const" in node:
        return json.dumps(node["const"])
    t = node.get("type")
    if t == "array":
        inner = _ts_type(node.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        extra = node.get("additionalProperties")
        if isinstance(extra, dict):
            return f"Record<string, {_ts_type(extra)}>"
        return "Record<string, unknown>"
    return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}.get(t, "unknown")


def typescript() -> str:
    # Python always writes every field, so the page sees none as optional.
    defs = json_schema("serialization")["$defs"]
    out = [
        "// Generated by `python -m schema.export` from schema/claim.py. Do not edit by hand.",
        "// A test fails when this file is stale.",
        "",
    ]
    for name in [m.__name__ for m in EXPORTED]:
        node = defs[name]
        if node.get("description"):
            out.append(f"/** {node['description'].strip().splitlines()[0]} */")
        out.append(f"export interface {name} {{")
        required = set(node.get("required", []))
        for prop, spec in node["properties"].items():
            if spec.get("description"):
                out.append(f"  /** {spec['description']} */")
            opt = "" if prop in required else "?"
            out.append(f"  {prop}{opt}: {_ts_type(spec)};")
        out.append("}")
        out.append("")
    return "\n".join(out)


def _rendered() -> dict[Path, str]:
    return {
        JSON_PATH: json.dumps(json_schema(), indent=2, sort_keys=False) + "\n",
        TS_PATH: typescript(),
    }


def main(argv: list[str]) -> int:
    stale = []
    for path, text in _rendered().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            if "--check" in argv:
                stale.append(path)
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
                print(f"wrote {path.relative_to(HERE.parent)}")
    for path in stale:
        print(f"stale: {path.relative_to(HERE.parent)}; run python -m schema.export")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
